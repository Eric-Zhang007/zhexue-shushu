    nian_liuqin = []
    # 年干看父亲（偏财定位）
    father_ss = get_shi_shen(day_gan, nian_gan)
    if father_ss in ('偏财', '正财'):
        nian_liuqin.append(f"年干{TIAN_GAN[nian_gan]}→父亲({father_ss})")
    # 年支看母亲（正印定位）
    if nian_zhi >= 0:
        cangs = ZHI_CANG_GAN[nian_zhi]
