            for mp in main_positions:
                if mp in hm:
                    val = hm[mp]
                    # 对于四天干串联 (三奇贵人), data的key是子串
                    if mp == 18:
                        for dk in data:
                            if dk in val:
                                zone = _pos_to_zone(mp)
                                result_map.setdefault(name, set()).add(zone)
                    # 普通整柱匹配: val是否在data的keys中
