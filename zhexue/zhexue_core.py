    result_map = {}  # name -> set of positions
    
    # 对每个神煞条目进行检查
    for entry in SHEN_SHA_DATA:
        name = entry["name"]
        main_str = entry["main"]
        tags_str = entry["tags"]
        sex_required = int(entry["sex"])
        data = entry["data"]
        
