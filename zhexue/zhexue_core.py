JIE_QI_NAMES = ['立春','惊蛰','清明','立夏','芒种','小暑','立秋','白露','寒露','立冬','大雪','小寒']

def flow_month(year, month, day):
    """
    返回当年12个节气月的流月信息。
    年柱由 year 推算, 月柱由五虎遁定, 十神以 day_gan 为日主。
    """
    y_gan = (year - 4) % 10
    day_gan, day_zhi = day_ganzhi_from_date(year, month, day)
    results = []
    # 节气索引: 0=立春(寅月), ..., 10=大雪(子月), 11=小寒(丑月)
    for i in range(12):
        # JIE_TERMS中 立春在[1], 惊蛰在[2], ..., 大雪在[11], 小寒在[0]
        jie_index = (i + 1) % 12
        tm, td = JIE_TERMS[jie_index]
        m_gan, m_zhi = month_gan(y_gan, i)
        results.append({
            'jieqi': JIE_QI_NAMES[i],
            'month': tm,
            'day': td,
            'ganzhi': f"{TIAN_GAN[m_gan]}{DI_ZHI[m_zhi]}",
            'shi_shen': get_shi_shen(day_gan, m_gan),
        })
    return results


def flow_day(start_date, days=30):
    """
    从 start_date 开始, 连续 days 天的流日干支。
    start_date: datetime.date or (year,month,day) tuple
    Yields dict with date, ganzhi.
    """
    if isinstance(start_date, (tuple, list)):
        start_date = datetime(*start_date)
    for i in range(days):
        d = start_date + timedelta(days=i)
        g, z = day_ganzhi_from_date(d.year, d.month, d.day)
        yield {
            'date': str(d.date()),
            'ganzhi': f"{TIAN_GAN[g]}{DI_ZHI[z]}",
        }


def flow_hour(date, hour, minute=0):
    """
    返回指定时刻的时柱。
    date: datetime.date or (year,month,day) tuple
    hour: 0-23
    minute: 0-59
    """
    if isinstance(date, (tuple, list)):
        date = datetime(*date)
    elif not isinstance(date, datetime):
        date = datetime(date.year, date.month, date.day)
    hz = hour_zhi_index(hour, minute)
    dg, dz = day_ganzhi_from_date(date.year, date.month, date.day)
    hg, hz2 = hour_ganzhi(dg, hz)
    return {
        'hour_zhi': hz,
        'hour_zhi_name': DI_ZHI[hz2],
        'ganzhi': f"{TIAN_GAN[hg]}{DI_ZHI[hz2]}",
    }


