# ========== 干支流通分析 ==========

def liutong_ganzhi(bazi_dict):
    """
    分析八字的天干流通和地支关系。
    参数: bazi_dict = {'nian':(gan,zhi), 'yue':(gan,zhi), 'ri':(gan,zhi), 'shi':(gan,zhi)}
    返回:
    {
        'tian_gan_sheng_ke': [('年→月','丁生己','相生'), ...],
        'tian_gan_chong_he': [('丁壬合','天干五合'), ...],
        'di_zhi_he': [('亥卯合木','地支六合'), ...],
        'di_zhi_chong': [('巳亥冲'), ...],
        'di_zhi_xing': [('丑戌相刑'), ...],
        'di_zhi_hai': [('子未相害'), ...],
        'gan_zhi_guanxi': [('丁坐亥(正官)','盖头/截脚'), ...],
        '流通分析': '年柱丁火生月柱己土...',
    }
    """
    result = {
        'tian_gan_sheng_ke': [],
        'tian_gan_chong_he': [],
        'di_zhi_he': [],
        'di_zhi_chong': [],
        'di_zhi_xing': [],
        'di_zhi_hai': [],
        'gan_zhi_guanxi': [],
        '流通分析': '',
    }

    pillars_order = ['nian', 'yue', 'ri', 'shi']
    gans = [bazi_dict[p][0] for p in pillars_order]
    zhis = [bazi_dict[p][1] for p in pillars_order]
    gan_names = [TIAN_GAN[g] for g in gans]
    zhi_names = [DI_ZHI[z] for z in zhis]

    # 天干五合
    WU_HE = {(0,5):'甲己合土',(5,0):'甲己合土',
             (1,6):'乙庚合金',(6,1):'乙庚合金',
             (2,7):'丙辛合水',(7,2):'丙辛合水',
             (3,8):'丁壬合木',(8,3):'丁壬合木',
             (4,9):'戊癸合火',(9,4):'戊癸合火'}

    # 相邻天干生克
    gan_pairs = [('年→月', gans[0], gans[1], gan_names[0], gan_names[1]),
                 ('月→日', gans[1], gans[2], gan_names[1], gan_names[2]),
                 ('日→时', gans[2], gans[3], gan_names[2], gan_names[3])]

    for label, g1, g2, n1, n2 in gan_pairs:
        # 五合
        if (g1, g2) in WU_HE:
            result['tian_gan_chong_he'].append((f"{n1}{n2}合", WU_HE[(g1,g2)]))
        elif (g2, g1) in WU_HE:
            result['tian_gan_chong_he'].append((f"{n1}{n2}合", WU_HE[(g2,g1)]))
        # 生克
        w1 = GAN_WUXING[n1]
        w2 = GAN_WUXING[n2]
        rel = wuxing_rel(w1, w2)
        if rel in ('wo_sheng', 'sheng_wo'):
            result['tian_gan_sheng_ke'].append((f"{n1}→{n2}", f"{n1}{w1}生{n2}{w2}", '相生'))
        elif rel in ('wo_ke', 'ke_wo'):
            result['tian_gan_sheng_ke'].append((f"{n1}→{n2}", f"{n1}{w1}克{n2}{w2}", '相克'))

    # 非相邻天干五合
    for i in range(4):
        for j in range(i+1, 4):
            if j - i > 1:
                g1, g2 = gans[i], gans[j]
                n1, n2 = gan_names[i], gan_names[j]
                p1, p2 = pillars_order[i], pillars_order[j]
                if (g1, g2) in WU_HE:
                    result['tian_gan_chong_he'].append((f"{n1}{n2}合({p1}{p2})", WU_HE[(g1,g2)]))
                elif (g2, g1) in WU_HE:
                    result['tian_gan_chong_he'].append((f"{n1}{n2}合({p1}{p2})", WU_HE[(g2,g1)]))

    # 地支六合
    LIU_HE = {(0,1):'子丑合土',(1,0):'子丑合土',
              (2,11):'寅亥合木',(11,2):'寅亥合木',
              (3,10):'卯戌合火',(10,3):'卯戌合火',
              (4,9):'辰酉合金',(9,4):'辰酉合金',
              (5,8):'巳申合水',(8,5):'巳申合水',
              (6,7):'午未合土',(7,6):'午未合土'}
    for i in range(4):
        for j in range(i+1, 4):
            z1, z2 = zhis[i], zhis[j]
            n1, n2 = zhi_names[i], zhi_names[j]
            if (z1, z2) in LIU_HE:
                result['di_zhi_he'].append((f"{n1}{n2}合", LIU_HE[(z1,z2)]))

    # 地支三合 (至少出现2个即算半合)
    SAN_HE_TRIOS = [
        (set([2,6,10]), '寅午戌三合火局'),
        (set([5,9,1]),  '巳酉丑三合金局'),
        (set([8,0,4]),  '申子辰三合水局'),
        (set([11,3,7]), '亥卯未三合木局'),
    ]
    for trio, name in SAN_HE_TRIOS:
        found = [z for z in zhis if z in trio]
        if len(found) >= 2:
            result['di_zhi_he'].append(('+'.join(DI_ZHI[z] for z in found), name))

    # 地支六冲
    LIU_CHONG = {(0,6):'子午相冲',(6,0):'子午相冲',
                 (1,7):'丑未相冲',(7,1):'丑未相冲',
                 (2,8):'寅申相冲',(8,2):'寅申相冲',
                 (3,9):'卯酉相冲',(9,3):'卯酉相冲',
                 (4,10):'辰戌相冲',(10,4):'辰戌相冲',
                 (5,11):'巳亥相冲',(11,5):'巳亥相冲'}
    for i in range(4):
        for j in range(i+1, 4):
            z1, z2 = zhis[i], zhis[j]
            if (z1, z2) in LIU_CHONG:
                result['di_zhi_chong'].append(LIU_CHONG[(z1,z2)])

    # 地支三刑
    SAN_XING = {(2,5):'寅巳相刑',(5,2):'寅巳相刑',
                (2,8):'寅申相刑',(8,2):'寅申相刑',
                (5,8):'巳申相刑',(8,5):'巳申相刑',
                (1,7):'丑未相刑',(7,1):'丑未相刑',
                (1,10):'丑戌相刑',(10,1):'丑戌相刑',
                (7,10):'未戌相刑',(10,7):'未戌相刑',
                (0,3):'子卯相刑',(3,0):'子卯相刑'}
    ZI_XING = {4:'辰自刑', 6:'午自刑', 9:'酉自刑', 11:'亥自刑'}
    for i in range(4):
        for j in range(i+1, 4):
            z1, z2 = zhis[i], zhis[j]
            if (z1, z2) in SAN_XING:
                result['di_zhi_xing'].append(SAN_XING[(z1,z2)])
    for z in zhis:
        if z in ZI_XING:
            result['di_zhi_xing'].append(ZI_XING[z])

    # 地支六害
    LIU_HAI = {(0,7):'子未相害',(7,0):'子未相害',
               (1,6):'丑午相害',(6,1):'丑午相害',
               (2,5):'寅巳相害',(5,2):'寅巳相害',
               (3,4):'卯辰相害',(4,3):'卯辰相害',
               (8,11):'申亥相害',(11,8):'申亥相害',
               (9,10):'酉戌相害',(10,9):'酉戌相害'}
    for i in range(4):
        for j in range(i+1, 4):
            z1, z2 = zhis[i], zhis[j]
            if (z1, z2) in LIU_HAI:
                result['di_zhi_hai'].append(LIU_HAI[(z1,z2)])

    # 天干坐支关系 (盖头/截脚)
    for i in range(4):
        gn, zn = gan_names[i], zhi_names[i]
        gw, zw = GAN_WUXING[gn], ZHI_WUXING[zn]
        p = pillars_order[i]
        if gw == zw:
            result['gan_zhi_guanxi'].append((f"{gn}坐{zn}({p})", f"{gw}{zw}同五行", '同'))
        elif wuxing_rel(gw, zw) == 'wo_ke':
            result['gan_zhi_guanxi'].append((f"{gn}坐{zn}({p})", f"{gw}克{zw}", '盖头'))
        elif wuxing_rel(gw, zw) == 'ke_wo':
            result['gan_zhi_guanxi'].append((f"{gn}坐{zn}({p})", f"{zw}克{gw}", '截脚'))
        elif wuxing_rel(gw, zw) == 'wo_sheng':
            result['gan_zhi_guanxi'].append((f"{gn}坐{zn}({p})", f"{gw}生{zw}", '天干生地支'))
        elif wuxing_rel(gw, zw) == 'sheng_wo':
            result['gan_zhi_guanxi'].append((f"{gn}坐{zn}({p})", f"{zw}生{gw}", '地支生天干'))

    # 流通分析
    flow_parts = []
    for i in range(3):
        n1, n2 = gan_names[i], gan_names[i+1]
        w1, w2 = GAN_WUXING[n1], GAN_WUXING[n2]
        rel = wuxing_rel(w1, w2)
        if rel == 'wo_sheng':
            flow_parts.append(f"{n1}({w1})生{n2}({w2})")
        elif rel == 'sheng_wo':
            flow_parts.append(f"{n2}({w2})生{n1}({w1})")
        elif rel == 'wo_ke':
            flow_parts.append(f"{n1}({w1})克{n2}({w2})")
        elif rel == 'ke_wo':
            flow_parts.append(f"{n2}({w2})克{n1}({w1})")
        else:
            flow_parts.append(f"{n1}({w1})与{n2}({w2})同五行")
    result['流通分析'] = '年柱' + '，'.join(flow_parts)

    return result


# ========== 十二宫位分析 ==========

def gongwei_fenxi(nian_gan, nian_zhi, yue_gan, yue_zhi, ri_gan, ri_zhi, shi_gan, shi_zhi, gender):
    """
    分析四柱对应的宫位含义。
    年柱: 祖上/父母宫, 1-16岁
    月柱: 父母/兄弟宫, 17-32岁
    日柱: 自己/配偶宫, 33-48岁
    时柱: 子女宫, 49-64岁
    """
    result = {}
    day_gan = ri_gan

    # 年柱
    nian_liuqin = []
    # 年干看父亲（偏财定位）
    father_ss = get_shi_shen(day_gan, nian_gan)
    if father_ss in ('偏财', '正财'):
        nian_liuqin.append(f"年干{TIAN_GAN[nian_gan]}→父亲({father_ss})")
    # 年支看母亲（正印定位）
    if nian_zhi >= 0:
        cangs = ZHI_CANG_GAN[nian_zhi]
        for c in cangs:
            ss = get_shi_shen(day_gan, c)
            if ss == '正印':
                nian_liuqin.append(f"年支{DI_ZHI[nian_zhi]}藏{TIAN_GAN[c]}→母亲(正印)")
    nian_liuqin.append(f"年干{TIAN_GAN[nian_gan]}:{father_ss}")
    result['nian'] = {
        'gongwei': '祖上/父母宫',
        'nianling': '1~16岁',
        'liuqin': nian_liuqin,
    }

    # 月柱
    yue_liuqin = []
    yue_liuqin.append(f"月干{TIAN_GAN[yue_gan]}:{get_shi_shen(day_gan, yue_gan)}")
    yue_liuqin.append(f"月支{DI_ZHI[yue_zhi]}宫:父母/兄弟环境")
    yue_ss = get_shi_shen(day_gan, yue_gan)
    if yue_ss in ('比肩', '劫财'):
        yue_liuqin.append(f"月干{yue_ss}→兄弟姐妹")
    elif yue_ss in ('正印', '偏印'):
        yue_liuqin.append(f"月干→母亲/长辈")
    elif yue_ss in ('正财', '偏财'):
        yue_liuqin.append(f"月干→父亲/财富")
    result['yue'] = {
        'gongwei': '父母/兄弟宫',
        'nianling': '17~32岁',
        'liuqin': yue_liuqin,
    }

    # 日柱
    ri_liuqin = [f"日干{TIAN_GAN[ri_gan]}={gender}命(自己)"]
    ri_liuqin.append(f"日支{DI_ZHI[ri_zhi]}=配偶宫")
    is_male = (gender == '男' or gender == 'male')
    spouse_ss = '正财' if is_male else '正官'
    ri_liuqin.append(f"配偶星: {spouse_ss}")
    result['ri'] = {
        'gongwei': '自己/配偶宫',
        'nianling': '33~48岁',
        'liuqin': ri_liuqin,
    }

    # 时柱
    shi_liuqin = []
    shi_liuqin.append(f"时干{TIAN_GAN[shi_gan]}:{get_shi_shen(day_gan, shi_gan)}")
    shi_liuqin.append(f"时支{DI_ZHI[shi_zhi]}宫:子女环境")
    shi_ss = get_shi_shen(day_gan, shi_gan)
    if shi_ss in ('食神', '伤官'):
        shi_liuqin.append(f"时干{shi_ss}→子女")
    elif shi_ss in ('正官', '七杀'):
        shi_liuqin.append(f"时干{shi_ss}→事业/子女")
    result['shi'] = {
        'gongwei': '子女宫',
        'nianling': '49~64岁',
        'liuqin': shi_liuqin,
    }

    return result


# ========== 六亲分析 ==========

def liuqin_fenxi(day_gan, nian_gan, nian_zhi, yue_gan, yue_zhi, ri_gan, ri_zhi, shi_gan, shi_zhi, gender):
    """
    六亲系统：
    男命: 正财=妻,偏财=父, 正印=母, 比肩=兄弟, 劫财=姐妹
    女命: 正官=夫, 七杀=情人/偏夫, 正印=母, 偏财=父
    """
    is_male = (gender == '男' or gender == 'male')
    result = {}

    # 父亲 - 偏财定位 (我克者, 同性)
    father_ss = '偏财'
    father_gan = None
    father_zhu = None
    for label, g in [('年柱', nian_gan), ('月柱', yue_gan), ('日柱', ri_gan), ('时柱', shi_gan)]:
        ss = get_shi_shen(day_gan, g)
        if ss == '偏财':
            father_gan = TIAN_GAN[g]
            father_zhu = label
            break
    if father_gan is None:
        # fallback: 年干
        father_gan = TIAN_GAN[nian_gan]
        father_zhu = '年柱(偏财定位)'
        father_ss = get_shi_shen(day_gan, nian_gan)
    result['father'] = {
        'person': '父亲',
        'zhuwei': father_zhu,
        'gan': father_gan,
        'shi_shen': father_ss,
    }

    # 母亲 - 正印定位 (生我者, 异性)
    mother_ss = '正印'
    mother_gan = None
    mother_zhu = None
    for label, g in [('年柱', nian_gan), ('月柱', yue_gan), ('日柱', ri_gan), ('时柱', shi_gan)]:
        ss = get_shi_shen(day_gan, g)
        if ss == '正印':
            mother_gan = TIAN_GAN[g]
            mother_zhu = label
            break
    if mother_gan is None:
        # fallback: 年支藏干寻正印
        for c in ZHI_CANG_GAN[nian_zhi]:
            ss = get_shi_shen(day_gan, c)
            if ss == '正印':
                mother_gan = TIAN_GAN[c]
                mother_zhu = f"年支藏干"
                break
    if mother_gan is None:
        mother_gan = TIAN_GAN[yue_gan]
        mother_zhu = '月柱'
        mother_ss = get_shi_shen(day_gan, yue_gan)
    result['mother'] = {
        'person': '母亲',
        'zhuwei': mother_zhu,
        'gan': mother_gan,
        'shi_shen': mother_ss,
    }

    # 配偶
    if is_male:
        spouse_ss = '正财'
        lover_ss = '偏财'
    else:
        spouse_ss = '正官'
        lover_ss = '七杀'
    spouse_gan = None
    spouse_zhu = None
    for label, g in [('年柱', nian_gan), ('月柱', yue_gan), ('日柱', ri_gan), ('时柱', shi_gan)]:
        ss = get_shi_shen(day_gan, g)
        if ss == spouse_ss:
            spouse_gan = TIAN_GAN[g]
            spouse_zhu = label
            break
    if spouse_gan is None:
        spouse_gan = TIAN_GAN[ri_zhi]  # fallback
        spouse_zhu = '日支(配偶宫)'
    result['spouse'] = {
        'person': '妻' if is_male else '夫',
        'zhuwei': spouse_zhu,
        'gan': spouse_gan,
        'shi_shen': spouse_ss,
        'spouse_palace': f"日支{DI_ZHI[ri_zhi]}",
    }

    # 子女
    children = []
    for label, g in [('时柱', shi_gan), ('月柱', yue_gan), ('年柱', nian_gan), ('日柱', ri_gan)]:
        ss = get_shi_shen(day_gan, g)
        if not is_male:  # 女命: 伤官=子, 食神=女
            if ss in ('伤官',):
                children.append({'person': '子(伤官)', 'zhuwei': label, 'gan': TIAN_GAN[g], 'shi_shen': ss})
            elif ss in ('食神',):
                children.append({'person': '女(食神)', 'zhuwei': label, 'gan': TIAN_GAN[g], 'shi_shen': ss})
        else:  # 男命: 食神=男, 伤官=女
            if ss in ('食神',):
                children.append({'person': '子(食神)', 'zhuwei': label, 'gan': TIAN_GAN[g], 'shi_shen': ss})
            elif ss in ('伤官',):
                children.append({'person': '女(伤官)', 'zhuwei': label, 'gan': TIAN_GAN[g], 'shi_shen': ss})
    if not children:
        # 时支藏干查食伤
        for c in ZHI_CANG_GAN[shi_zhi]:
            ss = get_shi_shen(day_gan, c)
            if ss in ('食神', '伤官'):
                children.append({'person': f"子({ss})" if (ss=='食神' and is_male) or (ss=='伤官' and not is_male) else f"女({ss})",
                                 'zhuwei': f"时支藏干", 'gan': TIAN_GAN[c], 'shi_shen': ss})
    result['children'] = children

    # 兄弟姐妹
    siblings = []
    for label, g in [('年柱', nian_gan), ('月柱', yue_gan), ('日柱', ri_gan), ('时柱', shi_gan)]:
        ss = get_shi_shen(day_gan, g)
        if ss in ('比肩', '劫财'):
            sibling_type = '兄弟' if (ss == '比肩' and is_male) or (ss == '劫财' and not is_male) else '姐妹'
            siblings.append({'person': sibling_type, 'zhuwei': label, 'gan': TIAN_GAN[g], 'shi_shen': ss})
    result['siblings'] = siblings

    return result


# ========== 流日计算 (移植自问真八字 LiuRiAdapter) ==========

MONTH_NAMES = ["正月", "二月", "三月", "四月", "五月", "六月",
               "七月", "八月", "九月", "十月", "冬月", "腊月"]


def compute_liuri(start_date_str, days=32):
    """
    移植问真八字 LiuRiAdapter.d() 逻辑。
    从 start_date_str ('YYYY年MM月DD日' 或 'YYYY-MM-DD') 开始，
    逐日使用 day_ganzhi_from_date() 计算连续 days 天的流日干支。

    Returns list[dict]:
        date, ganzhi, gan, zhi, gan_idx, zhi_idx, day_num, month_name, year, month, day
    """
    import re
    if '年' in start_date_str:
        m = re.match(r'(\d+)年(\d+)月(\d+)日', start_date_str)
        if not m:
            raise ValueError(f"无法解析日期: {start_date_str}")
        year, month, day = int(m.group(1)), int(m.group(2)), int(m.group(3))
    else:
        parts = start_date_str.split('-')
        year, month, day = int(parts[0]), int(parts[1]), int(parts[2])

    from datetime import date as date_cls, timedelta
    results = []
    for i in range(days):
        d = date_cls(year, month, day) + timedelta(days=i)
        g, z = day_ganzhi_from_date(d.year, d.month, d.day)
        ganzhi = TIAN_GAN[g] + DI_ZHI[z]
        results.append({
            'date': str(d),
            'ganzhi': ganzhi,
            'gan': TIAN_GAN[g],
            'zhi': DI_ZHI[z],
            'gan_idx': g,
            'zhi_idx': z,
            'day_num': d.day,
            'month_name': MONTH_NAMES[d.month - 1],
            'year': d.year,
            'month': d.month,
            'day': d.day,
        })
    return results


# ========== 流时计算 (移植自问真八字 initLiushiData + BZCore.q()) ==========

def compute_liushi(day_gan, extended=False):
    """
    移植问真八字 initLiushiData() 逻辑。
    基于日干 day_gan (0-9索引 或 '甲'~'癸'汉字),
    按五鼠遁 (hour_gan) 计算12或13个时辰。

    extended=False: 标准12支 (子~亥)
    extended=True: 13支 (子~亥 + 次日子时)

    Returns list[dict]:
        gan_idx, zhi_idx, gan, zhi, ganzhi, time_label, hour
    """
    if isinstance(day_gan, str):
        day_gan_idx = TIAN_GAN.index(day_gan)
    else:
        day_gan_idx = day_gan

    if extended:
        zhi_names = ["子", "丑", "寅", "卯", "辰", "巳",
                     "午", "未", "申", "酉", "戌", "亥", "子"]
        time_labels = ["00:00", "01:00", "03:00", "05:00", "07:00", "09:00",
                       "11:00", "13:00", "15:00", "17:00", "19:00", "21:00", "23:00"]
    else:
        zhi_names = ["子", "丑", "寅", "卯", "辰", "巳",
                     "午", "未", "申", "酉", "戌", "亥"]
        time_labels = ["23:00", "01:00", "03:00", "05:00", "07:00", "09:00",
                       "11:00", "13:00", "15:00", "17:00", "19:00", "21:00"]

    next_gan_idx = (day_gan_idx + 1) % 10  # 次日天干 (用于第13个)
    results = []
    for i, (zhi_name, time_label) in enumerate(zip(zhi_names, time_labels)):
        zhi_idx = DI_ZHI.index(zhi_name)
        gan_idx = day_gan_idx if i < 12 else next_gan_idx
        hg = hour_gan(gan_idx, zhi_idx)
        results.append({
            'gan_idx': hg,
            'zhi_idx': zhi_idx,
            'gan': TIAN_GAN[hg],
            'zhi': DI_ZHI[zhi_idx],
            'ganzhi': TIAN_GAN[hg] + DI_ZHI[zhi_idx],
            'time_label': time_label,
            'hour': int(time_label.split(':')[0]),
        })
    return results


