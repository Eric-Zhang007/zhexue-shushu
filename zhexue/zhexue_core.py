def liutong_ganzhi(bazi_dict):
    """
    分析八字的天干流通和地支关系。
    参数: bazi_dict = {'nian':(gan,zhi), 'yue':(gan,zhi), 'ri':(gan,zhi), 'shi':(gan,zhi)}
    返回:
    {
        'tian_gan_sheng_ke': [('年→月','丁生己','相生'), ...],
        'tian_gan_chong_he': [('丁壬合','天干五合'), ...],
        'di_zhi_he': [('亥卯合木','地支六合'), ...],
        'di_zhi_chong': [('巳亥冲'), ...],
        'di_zhi_xing': [('丑戌相刑'), ...],
        'di_zhi_hai': [('子未相害'), ...],
        'gan_zhi_guanxi': [('丁坐亥(正官)','盖头/截脚'), ...],
        '流通分析': '年柱丁火生月柱己土...',
    }
    """
    result = {
        'tian_gan_sheng_ke': [],
        'tian_gan_chong_he': [],
        'di_zhi_he': [],
        'di_zhi_chong': [],
        'di_zhi_xing': [],
        'di_zhi_hai': [],
        'gan_zhi_guanxi': [],
        '流通分析': '',
    }

    pillars_order = ['nian', 'yue', 'ri', 'shi']
    gans = [bazi_dict[p][0] for p in pillars_order]
    zhis = [bazi_dict[p][1] for p in pillars_order]
    gan_names = [TIAN_GAN[g] for g in gans]
    zhi_names = [DI_ZHI[z] for z in zhis]

    # 天干五合
    WU_HE = {(0,5):'甲己合土',(5,0):'甲己合土',
             (1,6):'乙庚合金',(6,1):'乙庚合金',
             (2,7):'丙辛合水',(7,2):'丙辛合水',
             (3,8):'丁壬合木',(8,3):'丁壬合木',
             (4,9):'戊癸合火',(9,4):'戊癸合火'}

    # 相邻天干生克
    gan_pairs = [('年→月', gans[0], gans[1], gan_names[0], gan_names[1]),
                 ('月→日', gans[1], gans[2], gan_names[1], gan_names[2]),
                 ('日→时', gans[2], gans[3], gan_names[2], gan_names[3])]

    for label, g1, g2, n1, n2 in gan_pairs:
        # 五合
        if (g1, g2) in WU_HE:
            result['tian_gan_chong_he'].append((f"{n1}{n2}合", WU_HE[(g1,g2)]))
        elif (g2, g1) in WU_HE:
            result['tian_gan_chong_he'].append((f"{n1}{n2}合", WU_HE[(g2,g1)]))
        # 生克
        w1 = GAN_WUXING[n1]
        w2 = GAN_WUXING[n2]
        rel = wuxing_rel(w1, w2)
        if rel in ('wo_sheng', 'sheng_wo'):
            result['tian_gan_sheng_ke'].append((f"{n1}→{n2}", f"{n1}{w1}生{n2}{w2}", '相生'))
        elif rel in ('wo_ke', 'ke_wo'):
            result['tian_gan_sheng_ke'].append((f"{n1}→{n2}", f"{n1}{w1}克{n2}{w2}", '相克'))

    # 非相邻天干五合
    for i in range(4):
        for j in range(i+1, 4):
            if j - i > 1:
                g1, g2 = gans[i], gans[j]
                n1, n2 = gan_names[i], gan_names[j]
                p1, p2 = pillars_order[i], pillars_order[j]
                if (g1, g2) in WU_HE:
                    result['tian_gan_chong_he'].append((f"{n1}{n2}合({p1}{p2})", WU_HE[(g1,g2)]))
                elif (g2, g1) in WU_HE:
                    result['tian_gan_chong_he'].append((f"{n1}{n2}合({p1}{p2})", WU_HE[(g2,g1)]))

    # 地支六合
    LIU_HE = {(0,1):'子丑合土',(1,0):'子丑合土',
              (2,11):'寅亥合木',(11,2):'寅亥合木',
              (3,10):'卯戌合火',(10,3):'卯戌合火',
              (4,9):'辰酉合金',(9,4):'辰酉合金',
              (5,8):'巳申合水',(8,5):'巳申合水',
              (6,7):'午未合土',(7,6):'午未合土'}
    for i in range(4):
        for j in range(i+1, 4):
            z1, z2 = zhis[i], zhis[j]
            n1, n2 = zhi_names[i], zhi_names[j]
            if (z1, z2) in LIU_HE:
                result['di_zhi_he'].append((f"{n1}{n2}合", LIU_HE[(z1,z2)]))

    # 地支三合 (至少出现2个即算半合)
    SAN_HE_TRIOS = [
        (set([2,6,10]), '寅午戌三合火局'),
        (set([5,9,1]),  '巳酉丑三合金局'),
        (set([8,0,4]),  '申子辰三合水局'),
        (set([11,3,7]), '亥卯未三合木局'),
    ]
    for trio, name in SAN_HE_TRIOS:
        found = [z for z in zhis if z in trio]
        if len(found) >= 2:
            result['di_zhi_he'].append(('+'.join(DI_ZHI[z] for z in found), name))

    # 地支六冲
    LIU_CHONG = {(0,6):'子午相冲',(6,0):'子午相冲',
                 (1,7):'丑未相冲',(7,1):'丑未相冲',
                 (2,8):'寅申相冲',(8,2):'寅申相冲',
                 (3,9):'卯酉相冲',(9,3):'卯酉相冲',
                 (4,10):'辰戌相冲',(10,4):'辰戌相冲',
                 (5,11):'巳亥相冲',(11,5):'巳亥相冲'}
    for i in range(4):
        for j in range(i+1, 4):
            z1, z2 = zhis[i], zhis[j]
            if (z1, z2) in LIU_CHONG:
                result['di_zhi_chong'].append(LIU_CHONG[(z1,z2)])

    # 地支三刑
    SAN_XING = {(2,5):'寅巳相刑',(5,2):'寅巳相刑',
                (2,8):'寅申相刑',(8,2):'寅申相刑',
                (5,8):'巳申相刑',(8,5):'巳申相刑',
                (1,7):'丑未相刑',(7,1):'丑未相刑',
                (1,10):'丑戌相刑',(10,1):'丑戌相刑',
                (7,10):'未戌相刑',(10,7):'未戌相刑',
                (0,3):'子卯相刑',(3,0):'子卯相刑'}
    ZI_XING = {4:'辰自刑', 6:'午自刑', 9:'酉自刑', 11:'亥自刑'}
    for i in range(4):
        for j in range(i+1, 4):
            z1, z2 = zhis[i], zhis[j]
            if (z1, z2) in SAN_XING:
                result['di_zhi_xing'].append(SAN_XING[(z1,z2)])
    for z in zhis:
        if z in ZI_XING:
            result['di_zhi_xing'].append(ZI_XING[z])

    # 地支六害
    LIU_HAI = {(0,7):'子未相害',(7,0):'子未相害',
               (1,6):'丑午相害',(6,1):'丑午相害',
               (2,5):'寅巳相害',(5,2):'寅巳相害',
               (3,4):'卯辰相害',(4,3):'卯辰相害',
               (8,11):'申亥相害',(11,8):'申亥相害',
               (9,10):'酉戌相害',(10,9):'酉戌相害'}
    for i in range(4):
        for j in range(i+1, 4):
            z1, z2 = zhis[i], zhis[j]
            if (z1, z2) in LIU_HAI:
                result['di_zhi_hai'].append(LIU_HAI[(z1,z2)])

    # 天干坐支关系 (盖头/截脚)
    for i in range(4):
        gn, zn = gan_names[i], zhi_names[i]
        gw, zw = GAN_WUXING[gn], ZHI_WUXING[zn]
        p = pillars_order[i]
        if gw == zw:
            result['gan_zhi_guanxi'].append((f"{gn}坐{zn}({p})", f"{gw}{zw}同五行", '同'))
        elif wuxing_rel(gw, zw) == 'wo_ke':
            result['gan_zhi_guanxi'].append((f"{gn}坐{zn}({p})", f"{gw}克{zw}", '盖头'))
        elif wuxing_rel(gw, zw) == 'ke_wo':
            result['gan_zhi_guanxi'].append((f"{gn}坐{zn}({p})", f"{zw}克{gw}", '截脚'))
        elif wuxing_rel(gw, zw) == 'wo_sheng':
            result['gan_zhi_guanxi'].append((f"{gn}坐{zn}({p})", f"{gw}生{zw}", '天干生地支'))
        elif wuxing_rel(gw, zw) == 'sheng_wo':
            result['gan_zhi_guanxi'].append((f"{gn}坐{zn}({p})", f"{zw}生{gw}", '地支生天干'))

    # 流通分析
    flow_parts = []
    for i in range(3):
        n1, n2 = gan_names[i], gan_names[i+1]
        w1, w2 = GAN_WUXING[n1], GAN_WUXING[n2]
        rel = wuxing_rel(w1, w2)
        if rel == 'wo_sheng':
            flow_parts.append(f"{n1}({w1})生{n2}({w2})")
        elif rel == 'sheng_wo':
            flow_parts.append(f"{n2}({w2})生{n1}({w1})")
        elif rel == 'wo_ke':
            flow_parts.append(f"{n1}({w1})克{n2}({w2})")
        elif rel == 'ke_wo':
            flow_parts.append(f"{n2}({w2})克{n1}({w1})")
        else:
            flow_parts.append(f"{n1}({w1})与{n2}({w2})同五行")
    result['流通分析'] = '年柱' + '，'.join(flow_parts)

    return result


