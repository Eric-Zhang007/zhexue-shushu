def shier_changsheng(gan_idx, zhi_idx):
    """
    返回某天干在地支上的十二长生状态。
    阳干顺行, 阴干逆行。
    gan_idx: 0-9 (甲乙丙丁戊己庚辛壬癸)
    zhi_idx: 0-11 (子丑寅卯辰巳午未申酉戌亥)
    """
    start = CHANG_SHENG_START[gan_idx]
    if gan_idx % 2 == 0:  # 阳干: 甲丙戊庚壬 — 顺行(递增)
        offset = (zhi_idx - start) % 12
    else:  # 阴干: 乙丁己辛癸 — 逆行(递减)
        offset = (start - zhi_idx) % 12
    return CHANG_SHENG_NAMES[offset]


