# ========== 六亲分析 ==========

def liuqin_fenxi(day_gan, nian_gan, nian_zhi, yue_gan, yue_zhi, ri_gan, ri_zhi, shi_gan, shi_zhi, gender):
    """
    六亲系统：
    男命: 正财=妻,偏财=父, 正印=母, 比肩=兄弟, 劫财=姐妹
    女命: 正官=夫, 七杀=情人/偏夫, 正印=母, 偏财=父
    """
    is_male = (gender == '男' or gender == 'male')
    result = {}

    # 父亲 - 偏财定位 (我克者, 同性)
    father_ss = '偏财'
    father_gan = None
    father_zhu = None
    for label, g in [('年柱', nian_gan), ('月柱', yue_gan), ('日柱', ri_gan), ('时柱', shi_gan)]:
        ss = get_shi_shen(day_gan, g)
        if ss == '偏财':
            father_gan = TIAN_GAN[g]
            father_zhu = label
            break
    if father_gan is None:
        # fallback: 年干
        father_gan = TIAN_GAN[nian_gan]
        father_zhu = '年柱(偏财定位)'
        father_ss = get_shi_shen(day_gan, nian_gan)
    result['father'] = {
        'person': '父亲',
        'zhuwei': father_zhu,
        'gan': father_gan,
        'shi_shen': father_ss,
    }

    # 母亲 - 正印定位 (生我者, 异性)
    mother_ss = '正印'
    mother_gan = None
    mother_zhu = None
    for label, g in [('年柱', nian_gan), ('月柱', yue_gan), ('日柱', ri_gan), ('时柱', shi_gan)]:
        ss = get_shi_shen(day_gan, g)
        if ss == '正印':
            mother_gan = TIAN_GAN[g]
            mother_zhu = label
            break
    if mother_gan is None:
        # fallback: 年支藏干寻正印
        for c in ZHI_CANG_GAN[nian_zhi]:
            ss = get_shi_shen(day_gan, c)
            if ss == '正印':
                mother_gan = TIAN_GAN[c]
                mother_zhu = f"年支藏干"
                break
    if mother_gan is None:
        mother_gan = TIAN_GAN[yue_gan]
        mother_zhu = '月柱'
        mother_ss = get_shi_shen(day_gan, yue_gan)
    result['mother'] = {
        'person': '母亲',
        'zhuwei': mother_zhu,
        'gan': mother_gan,
        'shi_shen': mother_ss,
    }

    # 配偶
    if is_male:
        spouse_ss = '正财'
        lover_ss = '偏财'
    else:
        spouse_ss = '正官'
        lover_ss = '七杀'
    spouse_gan = None
    spouse_zhu = None
    for label, g in [('年柱', nian_gan), ('月柱', yue_gan), ('日柱', ri_gan), ('时柱', shi_gan)]:
        ss = get_shi_shen(day_gan, g)
        if ss == spouse_ss:
            spouse_gan = TIAN_GAN[g]
            spouse_zhu = label
            break
    if spouse_gan is None:
        spouse_gan = TIAN_GAN[ri_zhi]  # fallback
        spouse_zhu = '日支(配偶宫)'
    result['spouse'] = {
        'person': '妻' if is_male else '夫',
        'zhuwei': spouse_zhu,
        'gan': spouse_gan,
        'shi_shen': spouse_ss,
        'spouse_palace': f"日支{DI_ZHI[ri_zhi]}",
    }

    # 子女
    children = []
    for label, g in [('时柱', shi_gan), ('月柱', yue_gan), ('年柱', nian_gan), ('日柱', ri_gan)]:
        ss = get_shi_shen(day_gan, g)
        if not is_male:  # 女命: 伤官=子, 食神=女
            if ss in ('伤官',):
                children.append({'person': '子(伤官)', 'zhuwei': label, 'gan': TIAN_GAN[g], 'shi_shen': ss})
            elif ss in ('食神',):
                children.append({'person': '女(食神)', 'zhuwei': label, 'gan': TIAN_GAN[g], 'shi_shen': ss})
        else:  # 男命: 食神=男, 伤官=女
            if ss in ('食神',):
                children.append({'person': '子(食神)', 'zhuwei': label, 'gan': TIAN_GAN[g], 'shi_shen': ss})
            elif ss in ('伤官',):
                children.append({'person': '女(伤官)', 'zhuwei': label, 'gan': TIAN_GAN[g], 'shi_shen': ss})
    if not children:
        # 时支藏干查食伤
        for c in ZHI_CANG_GAN[shi_zhi]:
            ss = get_shi_shen(day_gan, c)
            if ss in ('食神', '伤官'):
                children.append({'person': f"子({ss})" if (ss=='食神' and is_male) or (ss=='伤官' and not is_male) else f"女({ss})",
                                 'zhuwei': f"时支藏干", 'gan': TIAN_GAN[c], 'shi_shen': ss})
    result['children'] = children

    # 兄弟姐妹
    siblings = []
    for label, g in [('年柱', nian_gan), ('月柱', yue_gan), ('日柱', ri_gan), ('时柱', shi_gan)]:
        ss = get_shi_shen(day_gan, g)
        if ss in ('比肩', '劫财'):
            sibling_type = '兄弟' if (ss == '比肩' and is_male) or (ss == '劫财' and not is_male) else '姐妹'
            siblings.append({'person': sibling_type, 'zhuwei': label, 'gan': TIAN_GAN[g], 'shi_shen': ss})
    result['siblings'] = siblings

    return result


# ========== 流日计算 (移植自问真八字 LiuRiAdapter) ==========

MONTH_NAMES = ["正月", "二月", "三月", "四月", "五月", "六月",
               "七月", "八月", "九月", "十月", "冬月", "腊月"]


def compute_liuri(start_date_str, days=32):
    """
    移植问真八字 LiuRiAdapter.d() 逻辑。
    从 start_date_str ('YYYY年MM月DD日' 或 'YYYY-MM-DD') 开始，
    逐日使用 day_ganzhi_from_date() 计算连续 days 天的流日干支。

    Returns list[dict]:
        date, ganzhi, gan, zhi, gan_idx, zhi_idx, day_num, month_name, year, month, day
    """
    import re
    if '年' in start_date_str:
        m = re.match(r'(\d+)年(\d+)月(\d+)日', start_date_str)
        if not m:
            raise ValueError(f"无法解析日期: {start_date_str}")
        year, month, day = int(m.group(1)), int(m.group(2)), int(m.group(3))
    else:
        parts = start_date_str.split('-')
        year, month, day = int(parts[0]), int(parts[1]), int(parts[2])

    from datetime import date as date_cls, timedelta
    results = []
    for i in range(days):
        d = date_cls(year, month, day) + timedelta(days=i)
        g, z = day_ganzhi_from_date(d.year, d.month, d.day)
        ganzhi = TIAN_GAN[g] + DI_ZHI[z]
        results.append({
            'date': str(d),
            'ganzhi': ganzhi,
            'gan': TIAN_GAN[g],
            'zhi': DI_ZHI[z],
            'gan_idx': g,
            'zhi_idx': z,
            'day_num': d.day,
            'month_name': MONTH_NAMES[d.month - 1],
            'year': d.year,
            'month': d.month,
            'day': d.day,
        })
    return results


# ========== 流时计算 (移植自问真八字 initLiushiData + BZCore.q()) ==========

def compute_liushi(day_gan, extended=False):
    """
    移植问真八字 initLiushiData() 逻辑。
    基于日干 day_gan (0-9索引 或 '甲'~'癸'汉字),
    按五鼠遁 (hour_gan) 计算12或13个时辰。

    extended=False: 标准12支 (子~亥)
    extended=True: 13支 (子~亥 + 次日子时)

    Returns list[dict]:
        gan_idx, zhi_idx, gan, zhi, ganzhi, time_label, hour
    """
    if isinstance(day_gan, str):
        day_gan_idx = TIAN_GAN.index(day_gan)
    else:
        day_gan_idx = day_gan

    if extended:
        zhi_names = ["子", "丑", "寅", "卯", "辰", "巳",
                     "午", "未", "申", "酉", "戌", "亥", "子"]
        time_labels = ["00:00", "01:00", "03:00", "05:00", "07:00", "09:00",
                       "11:00", "13:00", "15:00", "17:00", "19:00", "21:00", "23:00"]
    else:
        zhi_names = ["子", "丑", "寅", "卯", "辰", "巳",
                     "午", "未", "申", "酉", "戌", "亥"]
        time_labels = ["23:00", "01:00", "03:00", "05:00", "07:00", "09:00",
                       "11:00", "13:00", "15:00", "17:00", "19:00", "21:00"]

    next_gan_idx = (day_gan_idx + 1) % 10  # 次日天干 (用于第13个)
    results = []
    for i, (zhi_name, time_label) in enumerate(zip(zhi_names, time_labels)):
        zhi_idx = DI_ZHI.index(zhi_name)
        gan_idx = day_gan_idx if i < 12 else next_gan_idx
        hg = hour_gan(gan_idx, zhi_idx)
        results.append({
            'gan_idx': hg,
            'zhi_idx': zhi_idx,
            'gan': TIAN_GAN[hg],
            'zhi': DI_ZHI[zhi_idx],
            'ganzhi': TIAN_GAN[hg] + DI_ZHI[zhi_idx],
            'time_label': time_label,
            'hour': int(time_label.split(':')[0]),
        })
    return results


