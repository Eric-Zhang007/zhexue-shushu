    mismatches = []
    app_lut = []
    our_lut = []

    for gan_idx in range(10):
        app_row = []
        our_row = []
        for zhi_idx in range(12):
            app_val = app_shier_changsheng(gan_idx, zhi_idx)
            our_val = shier_changsheng(gan_idx, zhi_idx)
