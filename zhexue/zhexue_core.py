        if sex_required != 0 and sex_required != sex_flag:
            continue
        
        # 解析main字段: 主位置
        main_positions = [int(x) for x in main_str.split(",")]
        # 解析tags字段: 目标位置
        tag_positions = [int(x) for x in tags_str.split(",")]
        
