# ========== 日干支计算 ★修正版★ ==========
# 1900-01-01 = 甲戌日 (天干0, 地支10)
# 验证通过: 2007-09-28=乙丑, 2024-02-10=甲辰
RI_GAN_REF = 0   # 甲
RI_ZHI_REF = 10  # 戌

def day_ganzhi_from_date(year, month, day):
    ref = datetime(1900, 1, 1)
    target = datetime(year, month, day)
    delta = (target - ref).days
    gan = (RI_GAN_REF + delta) % 10
    zhi = (RI_ZHI_REF + delta) % 12
    return gan, zhi

def hour_zhi_index(hour, minute=0):
    h = hour + minute / 60.0
    if h >= 23 or h < 1: return 0
    elif 1 <= h < 3: return 1
    elif 3 <= h < 5: return 2
    elif 5 <= h < 7: return 3
    elif 7 <= h < 9: return 4
    elif 9 <= h < 11: return 5
    elif 11 <= h < 13: return 6
    elif 13 <= h < 15: return 7
    elif 15 <= h < 17: return 8
    elif 17 <= h < 19: return 9
    elif 19 <= h < 21: return 10
    else: return 11

def hour_gan(day_gan_idx, hour_zhi_idx):
    """五鼠遁：日上起时"""
    start = (day_gan_idx * 2) % 10
    gan = (start + hour_zhi_idx) % 10
    return gan

def hour_ganzhi(day_gan_idx, hour_zhi_idx):
    g = hour_gan(day_gan_idx, hour_zhi_idx)
    return g, (hour_zhi_idx % 12)

