def calc_chenggu(year_ganzhi, lunar_month, lunar_day, hour_24):
    """
    称骨算命主函数

    Args:
        year_ganzhi: 年柱干支字符串，如 '甲子'
        lunar_month: 农历月份 (1-12)
        lunar_day: 农历日期 (1-30)
        hour_24: 24小时制时辰 (0-23)

    Returns:
        dict: {total_weight, weight_text, year_weight, month_weight,
               day_weight, hour_weight, interpretation}
    """
    # 时辰索引
    shichen_idx = hour_to_shichen_index(hour_24)

    # 各柱权重
    gz_idx = ganzhi_idx(year_ganzhi)
    y_w = YEAR_WEIGHT_BY_GANZHI_IDX[gz_idx]
    m_w = MONTH_WEIGHT[lunar_month]
    d_w = DAY_WEIGHT[lunar_day]
    h_w = HOUR_WEIGHT[shichen_idx]

    # 总和
    total = y_w + m_w + d_w + h_w
    weight_text = weight_to_text(total)

    # 查称骨歌
    liang = total // 10
    qian = total % 10
    result_id = weight_text

    interpretation = None
    if liang < 2 or (liang == 2 and qian == 0):
        interpretation = {
            'id': result_id,
            'types_man': '短命',
            'man': '二两以内不上书，谁要遇见赶着呼 。一世受贫无的怨，那世修来全比无。',
            'woman': '二两以内不上书，谁要遇见赶着呼 。一世受贫无的怨，那世修来全比无。',
        }
    else:
        for entry in CHENG_GU_GE:
            if entry['id'] == result_id:
                interpretation = entry
                break

    if interpretation is None:
        interpretation = {
            'id': result_id,
            'types_man': '未知',
            'man': '无对应称骨歌',
            'woman': '无对应称骨歌',
        }

    return {
        'total_weight': total,
        'weight_text': weight_text,
        'year_ganzhi': year_ganzhi,
        'year_weight': y_w,
        'month_weight': m_w,
        'day_weight': d_w,
        'hour_weight': h_w,
        'hour_index': shichen_idx,
        'interpretation': interpretation,
    }


def parse_hour_arg(hour_str):
    """解析时辰参数：支持24小时制数字(0-23) 或 地支字符(子-亥)
    返回24小时制小时数(0-23)"""
    h = hour_str.strip()
    # 地支字符 → 该时辰起始24小时值
    if h in SHI_CHEN:
        return SHI_CHEN_24H[SHI_CHEN.index(h)]
    try:
        val = int(h)
    except ValueError:
        raise ValueError(f"时辰参数无效: {hour_str}，应为0-23数字或地支(子丑寅卯辰巳午未申酉戌亥)")
    if 0 <= val <= 23:
        return val
    raise ValueError(f"时辰数字越界: {val}，应为0-23")


