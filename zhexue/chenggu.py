def ganzhi_idx(ganzhi_str):
    """返回六十甲子索引"""
    try:
        return JIA_ZI.index(ganzhi_str)
    except ValueError:
        return 0


def hour_to_shichen_index(hour_24):
    """24小时制转时辰索引 (0=子时, ..., 11=亥时)
    与 TimeUtil.f() 一致: (hour+1)//2, 0点→0, 1点→0, 23点→11"""
    idx = (hour_24 + 1) // 2
    if idx in (0, 12):
        return 0
    return idx


def weight_to_text(total_weight):
    """权重数转中文描述，如 32→'三两二钱', 40→'四两'"""
    liang = total_weight // 10
    qian = total_weight % 10
    if qian == 0:
        return f"{DIGIT_CN[liang]}两"
    else:
        return f"{DIGIT_CN[liang]}两{DIGIT_CN[qian]}钱"


